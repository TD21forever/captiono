export const LOAD_BILIBILI_CAPTIONS = "LOAD_BILIBILI_CAPTIONS";
export const BILIBILI_PAGE_SUBTITLE_SOURCE = "bilibili-page-subtitle";

const MAX_RESPONSE_BYTES = 5_000_000;
const REQUEST_TIMEOUT_MS = 8_000;

function cleanText(value) {
  return String(value ?? "")
    .replace(/<br\s*\/?>/gi, " ")
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/gi, " ")
    .replace(/&amp;/gi, "&")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    .replace(/&quot;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/\s+/g, " ")
    .trim();
}

function positiveInteger(value) {
  const number = Number(value);
  return Number.isSafeInteger(number) && number > 0 ? number : null;
}

function normalizeMediaId(value) {
  const mediaId = String(value ?? "").trim();
  return /^(?:BV[a-zA-Z0-9]+|ep\d+|ss\d+)$/.test(mediaId)
    ? mediaId
    : "";
}

function normalizeTrackId(value) {
  return String(value ?? "").trim().slice(0, 160);
}

function normalizeSubtitleUrl(value) {
  try {
    const raw = String(value ?? "").trim();
    const url = new URL(raw.startsWith("//") ? `https:${raw}` : raw);
    const hostname = url.hostname.toLowerCase();
    if (
      url.protocol !== "https:" ||
      (!hostname.endsWith(".hdslb.com") &&
        hostname !== "bilibili.com" &&
        !hostname.endsWith(".bilibili.com"))
    ) {
      return "";
    }
    url.hash = "";
    return url.href;
  } catch {
    return "";
  }
}

function trackId(track, index) {
  const authored = String(track?.id_str ?? track?.id ?? "")
    .trim()
    .replace(/[^a-zA-Z0-9._-]+/g, "-");
  const language = String(track?.lan ?? "und")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-");
  return `bilibili-${authored || `${language}-${index + 1}`}`;
}

function normalizeTracks(subtitles) {
  return (Array.isArray(subtitles) ? subtitles : [])
    .map((track, index) => {
      const subtitleUrl = normalizeSubtitleUrl(track?.subtitle_url);
      if (!subtitleUrl) return null;
      const language = String(track?.lan ?? "").trim();
      const label = cleanText(track?.lan_doc) || language || "字幕轨道";
      const autoGenerated =
        Number(track?.type) === 1 ||
        Number(track?.ai_type) > 0 ||
        /\bAI\b|自动/i.test(label);
      return {
        id: trackId(track, index),
        label,
        language,
        kind: "subtitles",
        mode: "disabled",
        readyState: "loaded",
        cueCount: null,
        autoGenerated,
        subtitleUrl,
      };
    })
    .filter(Boolean);
}

function languageMatches(track, requestedLanguage) {
  const available = String(track?.language ?? "").trim().toLowerCase();
  const requested = String(requestedLanguage ?? "").trim().toLowerCase();
  return Boolean(
    available &&
      requested &&
      (available === requested ||
        available.split("-", 1)[0] === requested.split("-", 1)[0]),
  );
}

function chooseTrack(tracks, request) {
  const requestedTrackId = normalizeTrackId(request.trackId);
  if (requestedTrackId) {
    return tracks.find((track) => track.id === requestedTrackId) ?? null;
  }
  const requestedLanguage = String(request.language ?? "").trim();
  if (requestedLanguage) {
    return (
      tracks.find(
        (track) =>
          languageMatches(track, requestedLanguage) && !track.autoGenerated,
      ) ??
      tracks.find((track) => languageMatches(track, requestedLanguage)) ??
      null
    );
  }
  return (
    tracks.find(
      (track) => languageMatches(track, "en") && !track.autoGenerated,
    ) ??
    tracks.find((track) => languageMatches(track, "en")) ??
    tracks.find((track) => !track.autoGenerated) ??
    tracks[0] ??
    null
  );
}

async function fetchJson(fetchImpl, url, { credentials = "include" } = {}) {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
  try {
    const response = await fetchImpl(url, {
      credentials,
      method: "GET",
      redirect: "error",
      signal: controller.signal,
    });
    if (!response.ok) {
      throw new Error(`Bilibili 字幕请求失败（HTTP ${response.status}）`);
    }
    const declaredLength = Number(response.headers?.get?.("content-length"));
    if (Number.isFinite(declaredLength) && declaredLength > MAX_RESPONSE_BYTES) {
      throw new Error("Bilibili 字幕响应过大，已停止读取。");
    }
    const body = await response.text();
    if (body.length > MAX_RESPONSE_BYTES) {
      throw new Error("Bilibili 字幕响应过大，已停止读取。");
    }
    return JSON.parse(body);
  } finally {
    clearTimeout(timeoutId);
  }
}

async function resolveVideoIdentity(request, fetchImpl) {
  const directAid = positiveInteger(request.aid);
  const directCid = positiveInteger(request.cid);
  const mediaId = normalizeMediaId(request.mediaId);
  if (directAid && directCid && !mediaId) {
    return { aid: directAid, cid: directCid, mediaId };
  }

  if (mediaId.startsWith("BV")) {
    const payload = await fetchJson(
      fetchImpl,
      `https://api.bilibili.com/x/web-interface/view?bvid=${encodeURIComponent(
        mediaId,
      )}`,
    );
    const data = payload?.data;
    const pageNumber = Math.max(1, positiveInteger(request.page) ?? 1);
    const selectedPage = Array.isArray(data?.pages)
      ? data.pages.find((page) => Number(page?.page) === pageNumber) ??
        data.pages[pageNumber - 1]
      : null;
    const aid = positiveInteger(data?.aid);
    const cid = positiveInteger(selectedPage?.cid ?? data?.cid);
    if (aid && cid) return { aid, cid, mediaId };
  }

  if (mediaId.startsWith("ep")) {
    const episodeId = positiveInteger(mediaId.slice(2));
    const payload = await fetchJson(
      fetchImpl,
      `https://api.bilibili.com/pgc/view/web/season?ep_id=${episodeId}`,
    );
    const episodes = payload?.result?.episodes;
    const episode = Array.isArray(episodes)
      ? episodes.find((item) => Number(item?.id) === episodeId)
      : null;
    const aid = positiveInteger(episode?.aid);
    const cid = positiveInteger(episode?.cid);
    if (aid && cid) return { aid, cid, mediaId };
  }

  if (mediaId.startsWith("ss")) {
    const seasonId = positiveInteger(mediaId.slice(2));
    const payload = await fetchJson(
      fetchImpl,
      `https://api.bilibili.com/pgc/view/web/season?season_id=${seasonId}`,
    );
    const episodes = payload?.result?.episodes;
    const pageNumber = Math.max(1, positiveInteger(request.page) ?? 1);
    const episode = Array.isArray(episodes)
      ? episodes[pageNumber - 1] ?? episodes[0]
      : null;
    const aid = positiveInteger(episode?.aid);
    const cid = positiveInteger(episode?.cid);
    if (aid && cid) return { aid, cid, mediaId };
  }

  throw new Error("无法确定当前 Bilibili 视频的字幕标识。");
}

function normalizeCues(payload) {
  const body = Array.isArray(payload?.body) ? payload.body : [];
  if (body.length > 50_000) {
    throw new Error("Bilibili 字幕片段过多，已停止读取。");
  }
  return body
    .map((cue, index) => {
      const startMs = Math.round(Number(cue?.from) * 1000);
      const endMs = Math.round(Number(cue?.to) * 1000);
      const text = cleanText(cue?.content);
      if (
        !Number.isFinite(startMs) ||
        !Number.isFinite(endMs) ||
        startMs < 0 ||
        endMs <= startMs ||
        !text
      ) {
        return null;
      }
      return {
        id: `bilibili-cue-${index + 1}`,
        sourceIndex: index,
        startMs,
        endMs,
        text,
        format: "bilibili-json",
      };
    })
    .filter(Boolean)
    .sort(
      (left, right) =>
        left.startMs - right.startMs || left.sourceIndex - right.sourceIndex,
    );
}

export function isBilibiliPage(value) {
  try {
    const hostname = new URL(value).hostname.toLowerCase();
    return hostname === "bilibili.com" || hostname.endsWith(".bilibili.com");
  } catch {
    return false;
  }
}

export async function loadBilibiliCaptions(request, fetchImpl = fetch) {
  const identity = await resolveVideoIdentity(request, fetchImpl);
  const manifest = await fetchJson(
    fetchImpl,
    `https://api.bilibili.com/x/player/wbi/v2?aid=${identity.aid}&cid=${identity.cid}`,
  );
  const tracks = normalizeTracks(manifest?.data?.subtitle?.subtitles);
  if (tracks.length === 0) {
    return {
      ok: false,
      reason: "bilibili-no-caption-tracks",
      message: "当前 Bilibili 视频没有提供可读取的字幕。",
      mediaId: identity.mediaId,
      tracks: [],
    };
  }

  const selected = chooseTrack(tracks, request);
  if (!selected) {
    return {
      ok: false,
      reason: "bilibili-caption-track-not-found",
      message: "当前 Bilibili 视频没有对应的字幕语言或轨道。",
      mediaId: identity.mediaId,
      tracks: tracks.map(({ subtitleUrl: _subtitleUrl, ...track }) => track),
    };
  }

  const subtitle = await fetchJson(fetchImpl, selected.subtitleUrl, {
    credentials: "omit",
  });
  const cues = normalizeCues(subtitle);
  const publicTracks = tracks.map(({ subtitleUrl: _subtitleUrl, ...track }) => ({
    ...track,
    isSelected: track.id === selected.id,
    mode: track.id === selected.id ? "hidden" : "disabled",
    cueCount: track.id === selected.id ? cues.length : null,
  }));
  if (cues.length === 0) {
    return {
      ok: false,
      reason: "bilibili-caption-track-empty",
      message: "所选 Bilibili 字幕轨为空。",
      mediaId: identity.mediaId,
      tracks: publicTracks,
    };
  }

  return {
    ok: true,
    source: BILIBILI_PAGE_SUBTITLE_SOURCE,
    mediaId: identity.mediaId,
    selectedTrackId: selected.id,
    language: { code: selected.language, label: selected.label },
    tracks: publicTracks,
    cues,
  };
}
